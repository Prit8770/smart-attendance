-- ====================================================================
-- DEPARTMENTS TABLE & RLS SETUP FOR SUPABASE (PostgreSQL)
-- ====================================================================
-- Run this SQL query in your Supabase Dashboard -> SQL Editor.

-- 1. Create departments table
CREATE TABLE IF NOT EXISTS public.departments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL,
  name TEXT NOT NULL,
  duration INTEGER NOT NULL CHECK (duration >= 1 AND duration <= 10),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Prevent duplicate department code or name (case-insensitive)
CREATE UNIQUE INDEX IF NOT EXISTS idx_departments_code_unique
  ON public.departments (UPPER(TRIM(code)));

CREATE UNIQUE INDEX IF NOT EXISTS idx_departments_name_unique
  ON public.departments (LOWER(TRIM(name)));

-- 3. Auto-update updated_at timestamp on edit
CREATE OR REPLACE FUNCTION public.set_departments_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_departments_updated_at ON public.departments;
CREATE TRIGGER trg_departments_updated_at
  BEFORE UPDATE ON public.departments
  FOR EACH ROW
  EXECUTE FUNCTION public.set_departments_updated_at();

-- 4. Enable Row Level Security (RLS) matching backend/rls_policies.sql
ALTER TABLE public.departments ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow backend full access on departments" ON public.departments;
CREATE POLICY "Allow backend full access on departments"
  ON public.departments
  FOR ALL
  USING (true)
  WITH CHECK (true);

