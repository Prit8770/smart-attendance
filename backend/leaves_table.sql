-- ====================================================================
-- LEAVES TABLE, FILE ATTACHMENT COLUMNS & RLS SETUP FOR SUPABASE
-- ====================================================================
-- Run this SQL query in your Supabase Dashboard -> SQL Editor.

-- 1. Create leaves table (stores student leave details + uploaded PDF/Photo file)
CREATE TABLE IF NOT EXISTS public.leaves (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id TEXT NOT NULL,
  enrollment_no TEXT NOT NULL,
  student_enrollment TEXT,
  email TEXT,
  roll_no TEXT DEFAULT '',
  student_name TEXT NOT NULL,
  course TEXT DEFAULT '',
  semester TEXT DEFAULT '',
  division TEXT DEFAULT '',
  type TEXT NOT NULL DEFAULT 'Personal Leave',
  recipient_id TEXT NOT NULL DEFAULT 'ADMIN',
  recipient_name TEXT DEFAULT 'Admin',
  from_date DATE NOT NULL,
  to_date DATE NOT NULL,
  reason TEXT NOT NULL,
  attachment TEXT,              -- Stores uploaded PDF/Image Base64 Data URL or file URL
  file_name TEXT,               -- Stores uploaded file name (e.g. medical_note.pdf)
  file_type TEXT,               -- Optional MIME type (e.g. application/pdf, image/png)
  file_size BIGINT,             -- Optional file size in bytes
  status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  admin_remarks TEXT DEFAULT '',
  reviewed_by TEXT DEFAULT '',
  reviewed_at TIMESTAMPTZ,
  date_submitted DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Performance indexes for student / faculty / admin queries
CREATE INDEX IF NOT EXISTS idx_leaves_student_id ON public.leaves (student_id);
CREATE INDEX IF NOT EXISTS idx_leaves_enrollment_no ON public.leaves (enrollment_no);
CREATE INDEX IF NOT EXISTS idx_leaves_recipient_id ON public.leaves (recipient_id);
CREATE INDEX IF NOT EXISTS idx_leaves_status ON public.leaves (status);
CREATE INDEX IF NOT EXISTS idx_leaves_created_at ON public.leaves (created_at DESC);

-- 3. Enable Row Level Security (RLS) matching backend/rls_policies.sql
ALTER TABLE public.leaves ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow backend full access on leaves" ON public.leaves;
CREATE POLICY "Allow backend full access on leaves"
  ON public.leaves
  FOR ALL
  USING (true)
  WITH CHECK (true);

